    /** Vẽ nền (giấy an ninh có hoa văn), khung, dải tiêu đề và ghi chú mô phỏng cho mỗi trang. */
    private final class InvoiceFrame extends PdfPageEventHelper {
        private final PaymentReceiptData data;
        private final String serial;
        private final String number;

        InvoiceFrame(PaymentReceiptData data, String serial, String number) {
            this.data = data;
            this.serial = serial;
            this.number = number;
        }

        @Override
        public void onEndPage(PdfWriter writer, Document document) {
            Rectangle page = document.getPageSize();
            float w = page.getWidth();
            float h = page.getHeight();
            try {
                background(writer.getDirectContentUnder(), w, h);
                foreground(writer.getDirectContent(), w, h);
            } catch (IOException e) {
                throw new IllegalStateException(e);
            }
        }

        private void background(PdfContentByte cb, float w, float h) throws IOException {
            // nền giấy
            cb.saveState();
            cb.setColorFill(new Color(0xFA, 0xFB, 0xFE));
            cb.rectangle(0, 0, w, h);
            cb.fill();
            cb.restoreState();

            // hoa văn rosette đồng tâm + logo mờ ở giữa trang
            float cx = w / 2;
            float cy = h / 2 - 20;
            cb.saveState();
            cb.setGState(opacity(0.10f));
            cb.setColorStroke(NAVY);
            cb.setLineWidth(0.35f);
            for (int k = 0; k < 7; k++) {
                float base = 52 + k * 26;
                for (int i = 0; i <= 720; i++) {
                    double th = Math.toRadians(i * 0.5);
                    double r = base + 7 * Math.sin(14 * th + k * 0.9);
                    float x = (float) (cx + r * Math.cos(th));
                    float y = (float) (cy + r * Math.sin(th));
                    if (i == 0) cb.moveTo(x, y); else cb.lineTo(x, y);
                }
                cb.closePathStroke();
            }
            cb.restoreState();

            cb.saveState();
            cb.setGState(opacity(0.07f));
            Image mark = Image.getInstance(logoNavy);
            mark.scaleToFit(230, 230);
            mark.setAbsolutePosition(cx - mark.getScaledWidth() / 2, cy - mark.getScaledHeight() / 2);
            cb.addImage(mark);
            cb.restoreState();

            // chữ chéo mờ
            cb.saveState();
            cb.setGState(opacity(0.05f));
            cb.setColorFill(NAVY);
            cb.beginText();
            cb.setFontAndSize(bold, 54);
            double ang = Math.toRadians(33);
            cb.setTextMatrix((float) Math.cos(ang), (float) Math.sin(ang), (float) -Math.sin(ang), (float) Math.cos(ang),
                    w / 2 - 205, h / 2 - 150);
            cb.showText("HÓA ĐƠN MÔ PHỎNG");
            cb.endText();
            cb.restoreState();

            // dải sóng guilloche ở đáy
            for (int k = 0; k < 4; k++) {
                cb.saveState();
                cb.setGState(opacity(k % 2 == 0 ? 0.35f : 0.22f));
                cb.setColorStroke(k % 2 == 0 ? NAVY : GOLD);
                cb.setLineWidth(0.5f);
                for (float x = 24; x <= w - 24; x += 2) {
                    float y = 30 + 4.5f * (float) Math.sin((x / 22.0) + k * 0.8);
                    if (x == 24) cb.moveTo(x, y); else cb.lineTo(x, y);
                }
                cb.stroke();
                cb.restoreState();
            }
        }

        private void foreground(PdfContentByte cb, float w, float h) throws IOException {
            // khung ngoài vàng + khung trong xanh
            cb.saveState();
            cb.setColorStroke(GOLD);
            cb.setLineWidth(1.4f);
            cb.roundRectangle(14, 14, w - 28, h - 28, 8);
            cb.stroke();
            cb.setColorStroke(NAVY);
            cb.setLineWidth(0.5f);
            cb.roundRectangle(19, 19, w - 38, h - 38, 6);
            cb.stroke();
            cb.restoreState();

            // dải tiêu đề
            float bandH = 90;
            float bandY = h - 24 - bandH;
            cb.saveState();
            cb.setColorFill(DEEP);
            cb.roundRectangle(24, bandY, w - 48, bandH, 6);
            cb.fill();
            cb.setColorFill(GOLD);
            cb.rectangle(24, bandY - 2.2f, w - 48, 2.2f);
            cb.fill();
            cb.restoreState();

            Image mark = Image.getInstance(logoWhite);
            mark.scaleToFit(58, 58);
            mark.setAbsolutePosition(40, bandY + (bandH - mark.getScaledHeight()) / 2);
            cb.addImage(mark);

            text(cb, bold, 24, Color.WHITE, 108, bandY + 50, "LegacyVault", PdfContentByte.ALIGN_LEFT);
            text(cb, regular, 9, new Color(0xC9, 0xD0, 0xE8), 109, bandY + 30, SELLER_WEBSITE, PdfContentByte.ALIGN_LEFT);

            float rx = w - 40;
            text(cb, bold, 16, Color.WHITE, rx, bandY + 58, "HÓA ĐƠN GIÁ TRỊ GIA TĂNG", PdfContentByte.ALIGN_RIGHT);
            text(cb, regular, 9, new Color(0xE3, 0xC9, 0x8F), rx, bandY + 43, "(VAT INVOICE)", PdfContentByte.ALIGN_RIGHT);
            text(cb, regular, 8, new Color(0xC9, 0xD0, 0xE8), rx, bandY + 29, "Bản thể hiện của hóa đơn điện tử", PdfContentByte.ALIGN_RIGHT);

            // nhãn MÔ PHỎNG
            cb.saveState();
            cb.setColorFill(GOLD);
            cb.roundRectangle(rx - 116, bandY + 8, 116, 14, 7);
            cb.fill();
            cb.restoreState();
            text(cb, bold, 8, DEEP, rx - 58, bandY + 12, "MÔ PHỎNG / SIMULATED", PdfContentByte.ALIGN_CENTER);

            // ghi chú mô phỏng ở chân trang
            float noteX = 36;
            float noteW = w - 72;
            float noteY = 40;
            float noteH = 66;
            cb.saveState();
            cb.setColorFill(new Color(0xFD, 0xF3, 0xF3));
            cb.setColorStroke(RED);
            cb.setLineWidth(0.8f);
            cb.roundRectangle(noteX, noteY, noteW, noteH, 4);
            cb.fillStroke();
            cb.restoreState();
            com.lowagie.text.pdf.ColumnText ct = new com.lowagie.text.pdf.ColumnText(cb);
            ct.setSimpleColumn(noteX + 8, noteY + 3, noteX + noteW - 8, noteY + noteH - 4);
            Paragraph note = new Paragraph();
            note.setLeading(11);
            note.add(new Phrase("Lưu ý: ", font(bold, 8.5f, RED)));
            note.add(new Phrase(SIMULATION_NOTE, font(regular, 8.5f, INK)));
            Paragraph noteEn = new Paragraph();
            noteEn.setLeading(11);
            noteEn.setSpacingBefore(2);
            noteEn.add(new Phrase("Note: ", font(bold, 8, RED)));
            noteEn.add(new Phrase(SIMULATION_NOTE_EN, font(regular, 8, MUTED)));
            ct.addElement(note);
            ct.addElement(noteEn);
            try {
                ct.go();
            } catch (com.lowagie.text.DocumentException e) {
                throw new IllegalStateException(e);
            }
            text(cb, regular, 7, MUTED, w - 40, noteY - 9, "Tra cứu: " + SELLER_WEBSITE + " · Mã tra cứu " + data.receiptNo()
                    + " · " + serial + "/" + number, PdfContentByte.ALIGN_RIGHT);
        }
    }

