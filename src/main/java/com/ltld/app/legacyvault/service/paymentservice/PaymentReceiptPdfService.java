    public byte[] render(PaymentReceiptData d) {
        String serial = invoiceSerial(d.issuedAt());
        String number = String.format(Locale.ROOT, "%07d", d.invoiceNumber());
        ByteArrayOutputStream out = new ByteArrayOutputStream();
        Document doc = new Document(PageSize.A4, MARGIN_X, MARGIN_X, MARGIN_TOP, MARGIN_BOTTOM);
        try {
            PdfWriter writer = PdfWriter.getInstance(doc, out);
            writer.setPageEvent(new InvoiceFrame(d, serial, number));
            doc.addTitle("Hóa đơn GTGT (mô phỏng) " + serial + " - " + number);
            doc.addSubject("Hóa đơn mô phỏng " + d.receiptNo());
            doc.addCreator("LegacyVault");
            doc.open();

            doc.add(infoRow(d, serial, number));

            doc.add(sectionTitle("ĐƠN VỊ BÁN HÀNG (SELLER)"));
            PdfPTable seller = table(new float[]{30, 70});
            row(seller, "Tên đơn vị (Company)", SELLER_NAME);
            row(seller, "Mã số thuế (Tax code)", SELLER_TAX_CODE);
            row(seller, "Địa chỉ (Address)", SELLER_ADDRESS);
            doc.add(seller);

            doc.add(sectionTitle("NGƯỜI MUA HÀNG (BUYER)"));
            PdfPTable buyer = table(new float[]{30, 70});
            row(buyer, "Họ tên người mua (Buyer name)", blankToDash(d.customerName()));
            row(buyer, "Đơn vị / MST (Company)", "—");
            row(buyer, "Email (Invoice email)", d.customerEmail());
            doc.add(buyer);

            doc.add(spacer(10));
            doc.add(items(d));
            doc.add(spacer(8));
            doc.add(summary(d));
            doc.add(spacer(8));
            doc.add(words(d));
            doc.add(spacer(10));
            doc.add(signatures(d));
        } catch (RuntimeException | IOException e) {
            throw new IllegalStateException("Cannot render invoice PDF", e);
        } finally {
            if (doc.isOpen()) {
                doc.close();
            }
        }
        return out.toByteArray();
    }

