    /** Hàng đầu: mã QR, ngày lập + mã tra cứu + mã cơ quan thuế giả lập, khối ký hiệu / số. */
    private PdfPTable infoRow(PaymentReceiptData d, String serial, String number) throws IOException {
        PdfPTable t = new PdfPTable(new float[]{19, 43, 38});
        t.setWidthPercentage(100);

        PdfPCell qr = noBorder();
        qr.setVerticalAlignment(Element.ALIGN_MIDDLE);
        Image qrImage = Image.getInstance(qrPng(qrPayload(d, serial, number)));
        qrImage.scaleToFit(82, 82);
        qr.addElement(qrImage);
        t.addCell(qr);

        PdfPCell mid = noBorder();
        mid.setVerticalAlignment(Element.ALIGN_MIDDLE);
        mid.setPaddingLeft(6);
        Paragraph day = new Paragraph("Ngày " + d.issuedAt().format(DAY) + " tháng " + d.issuedAt().format(MONTH)
                + " năm " + d.issuedAt().format(YEAR), font(bold, 11, NAVY));
        day.setSpacingAfter(1);
        mid.addElement(day);
        Paragraph dayEn = new Paragraph("Date: " + d.issuedAt().format(DAY_EN), font(regular, 8.5f, MUTED));
        dayEn.setSpacingAfter(4);
        mid.addElement(dayEn);
        mid.addElement(new Paragraph("Mã tra cứu (Lookup code): " + d.receiptNo(), font(regular, 8.5f, INK)));
        Paragraph tax = new Paragraph("Mã của cơ quan thuế (Tax authority code, giả lập):", font(regular, 7.5f, MUTED));
        tax.setSpacingBefore(3);
        mid.addElement(tax);
        mid.addElement(new Paragraph(taxAuthorityCode(d), font(regular, 7.5f, MUTED)));
        t.addCell(mid);

        PdfPCell right = noBorder();
        right.setVerticalAlignment(Element.ALIGN_MIDDLE);
        PdfPTable sn = new PdfPTable(new float[]{62, 38});
        sn.setWidthPercentage(100);
        serialRow(sn, "Ký hiệu mẫu số (Form):", FORM_CODE, INK);
        serialRow(sn, "Ký hiệu hóa đơn (Serial):", serial, INK);
        serialRow(sn, "Số hóa đơn (No.):", number, RED);
        right.addElement(sn);
        t.addCell(right);
        return t;
    }

    private void serialRow(PdfPTable t, String label, String value, Color valueColor) {
        PdfPCell l = noBorder();
        l.setPadding(2);
        l.addElement(new Phrase(label, font(regular, 8.5f, MUTED)));
        t.addCell(l);
        PdfPCell v = noBorder();
        v.setPadding(2);
        v.setHorizontalAlignment(Element.ALIGN_RIGHT);
        Paragraph p = new Paragraph(value, font(bold, 10.5f, valueColor));
        p.setAlignment(Element.ALIGN_RIGHT);
        v.addElement(p);
        t.addCell(v);
    }

    private PdfPTable items(PaymentReceiptData d) {
        long net = netAmount(d.amountVnd());
        PdfPTable t = table(new float[]{8, 38, 10, 8, 18, 18});
        String[] heads = {"STT\n(No.)", "Tên hàng hóa, dịch vụ\n(Description)", "ĐVT\n(Unit)", "SL\n(Qty)", "Đơn giá\n(Unit price)", "Thành tiền\n(Amount)"};
        for (int i = 0; i < heads.length; i++) {
            header(t, heads[i], i >= 4 ? Element.ALIGN_RIGHT : Element.ALIGN_LEFT);
        }
        String service = "Gói dịch vụ LegacyVault " + (d.planName() != null ? d.planName() : "")
                + (d.planCode() != null ? " (" + d.planCode() + ")" : "")
                + (d.durationDays() != null ? " - " + d.durationDays() + " ngày" : "");
        t.addCell(cell("1", regular, 9, Element.ALIGN_LEFT));
        t.addCell(cell(service.replace("  ", " ").trim(), regular, 9, Element.ALIGN_LEFT));
        t.addCell(cell("Gói", regular, 9, Element.ALIGN_LEFT));
        t.addCell(cell("1", regular, 9, Element.ALIGN_LEFT));
        t.addCell(cell(vnd(net), regular, 9, Element.ALIGN_RIGHT));
        t.addCell(cell(vnd(net), regular, 9, Element.ALIGN_RIGHT));
        return t;
    }

    /** Trái: thông tin thanh toán. Phải: cộng tiền hàng, thuế GTGT, tổng cộng. */
    private PdfPTable summary(PaymentReceiptData d) {
        long net = netAmount(d.amountVnd());
        long vat = d.amountVnd() - net;

        PdfPTable outer = new PdfPTable(new float[]{50, 50});
        outer.setWidthPercentage(100);

        PdfPCell left = noBorder();
        left.setPaddingRight(10);
        PdfPTable pay = new PdfPTable(new float[]{52, 48});
        pay.setWidthPercentage(100);
        payRow(pay, "Phương thức (Method)", "Trực tuyến qua " + d.paymentMethod());
        payRow(pay, "Ngân hàng (Bank)", blankToDash(d.vnpBankCode()));
        payRow(pay, "Mã giao dịch (Txn ID)", blankToDash(d.vnpTransactionNo()));
        payRow(pay, "Thanh toán lúc (Paid at)", fmt(d.paidAt()));
        payRow(pay, "Trạng thái (Status)", "Đã thanh toán (Paid)");
        left.addElement(pay);
        outer.addCell(left);

        PdfPCell right = noBorder();
        PdfPTable sum = table(new float[]{58, 42});
        sumRow(sum, "Cộng tiền hàng (Subtotal)", vnd(net), false);
        sumRow(sum, "Thuế suất GTGT (VAT rate)", VAT_PERCENT + "%", false);
        sumRow(sum, "Tiền thuế GTGT (VAT amount)", vnd(vat), false);
        sumRow(sum, "Tổng cộng (Total)", vnd(d.amountVnd()), true);
        right.addElement(sum);
        outer.addCell(right);
        return outer;
    }

