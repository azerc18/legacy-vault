    /** Ký hiệu hoá đơn: C (có mã cơ quan thuế) + 2 số cuối của năm + T (hoá đơn điện tử) + 2 ký tự tự chọn. */
    static String invoiceSerial(LocalDateTime issuedAt) {
        return "C" + String.format(Locale.ROOT, "%02d", issuedAt.getYear() % 100) + "TLV";
    }

    /** Số tiền chưa thuế khi giá đã bao gồm thuế GTGT. */
    static long netAmount(long grossVnd) {
        return Math.round(grossVnd * 100.0 / (100 + VAT_PERCENT));
    }

    /** Mã cơ quan thuế GIẢ LẬP (34 ký tự), cố định cho mỗi hoá đơn nên tải lại vẫn y hệt. */
    static String taxAuthorityCode(PaymentReceiptData d) {
        try {
            byte[] hash = MessageDigest.getInstance("SHA-256")
                    .digest((d.receiptNo() + "|" + d.transactionId()).getBytes(StandardCharsets.UTF_8));
            StringBuilder sb = new StringBuilder();
            for (byte b : hash) {
                sb.append(String.format(Locale.ROOT, "%02X", b));
            }
            return sb.substring(0, 34);
        } catch (NoSuchAlgorithmException e) {
            throw new IllegalStateException(e);
        }
    }

    /** Nội dung mã QR: chuỗi tra cứu giả lập, quét bằng điện thoại sẽ thấy rõ là hoá đơn mô phỏng. */
    static String qrPayload(PaymentReceiptData d, String serial, String number) {
        return "LEGACYVAULT|HOA-DON-MO-PHONG|" + FORM_CODE + "|" + serial + "|" + number + "|"
                + d.issuedAt().format(YMD) + "|" + d.amountVnd() + "|" + d.receiptNo();
    }

    private static byte[] qrPng(String text) throws IOException {
        try {
            Map<EncodeHintType, Object> hints = new EnumMap<>(EncodeHintType.class);
            hints.put(EncodeHintType.ERROR_CORRECTION, ErrorCorrectionLevel.M);
            hints.put(EncodeHintType.MARGIN, 0);
            hints.put(EncodeHintType.CHARACTER_SET, "UTF-8");
            BitMatrix m = new QRCodeWriter().encode(text, BarcodeFormat.QR_CODE, 0, 0, hints);
            int scale = 8;
            int quiet = 2;
            int size = (m.getWidth() + quiet * 2) * scale;
            BufferedImage img = new BufferedImage(size, size, BufferedImage.TYPE_INT_RGB);
            for (int y = 0; y < size; y++) {
                for (int x = 0; x < size; x++) {
                    int mx = x / scale - quiet;
                    int my = y / scale - quiet;
                    boolean dark = mx >= 0 && my >= 0 && mx < m.getWidth() && my < m.getHeight() && m.get(mx, my);
                    img.setRGB(x, y, dark ? DEEP.getRGB() : 0xFFFFFF);
                }
            }
            ByteArrayOutputStream bos = new ByteArrayOutputStream();
            ImageIO.write(img, "png", bos);
            return bos.toByteArray();
        } catch (com.google.zxing.WriterException e) {
            throw new IOException(e);
        }
    }

