    private PdfPCell cell(String text, BaseFont bf, float size, int align) {
        PdfPCell c = new PdfPCell(new Phrase(text == null ? "—" : text, font(bf, size, INK)));
        c.setPadding(5);
        c.setBorderColor(BORDER);
        c.setHorizontalAlignment(align);
        return c;
    }

